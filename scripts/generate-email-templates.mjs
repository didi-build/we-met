#!/usr/bin/env node
/**
 * Writes src/email/templates/generated.ts from the six source template files.
 * Run after editing *.html / *.txt under src/email/templates/.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const templateDir = join(repoRoot, "src/email/templates");

const FILES = [
  ["visitorFollowupHtml", "visitor-followup.html"],
  ["visitorFollowupText", "visitor-followup.txt"],
  ["ownerNewLeadHtml", "owner-new-lead.html"],
  ["ownerNewLeadText", "owner-new-lead.txt"],
  ["ownerDetailsUpdateHtml", "owner-details-update.html"],
  ["ownerDetailsUpdateText", "owner-details-update.txt"],
];

export function buildGeneratedEmailTemplatesSource() {
  const lines = [
    "/**",
    " * @generated by scripts/generate-email-templates.mjs — do not edit.",
    " * Regenerate: npm run email-templates:generate",
    " */",
    "",
  ];
  for (const [exportName, fileName] of FILES) {
    const content = readFileSync(join(templateDir, fileName), "utf8");
    lines.push(`export const ${exportName} = ${JSON.stringify(content)};`, "");
  }
  return `${lines.join("\n")}\n`;
}

function runCli() {
  if (process.argv.includes("--stdout")) {
    process.stdout.write(buildGeneratedEmailTemplatesSource());
    return;
  }
  const outPath = join(templateDir, "generated.ts");
  writeFileSync(outPath, buildGeneratedEmailTemplatesSource(), "utf8");
  console.log(`Wrote ${outPath}`);
}

const isMain =
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  runCli();
}
